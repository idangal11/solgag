export function buildSeedListings(now = Date.now()): Listing[] {
  return raw.map(({ shape, usableRatio, daysAgo, ...rest }) => {
    const polygon: LatLng[] = illustrativeFootprint(rest.center, shape.w, shape.l, shape.rot, shape.notch);
    const totalAreaSqm = Math.round(polygonAreaSqm(polygon));
    return {
      ...rest,
      polygon,
      polygonIllustrative: true,
      totalAreaSqm,
      usableAreaSqm: Math.round((totalAreaSqm * usableRatio) / 10) * 10,
      areaSource: 'polygon',
      images: [],
      createdAt: new Date(now - daysAgo * 86_400_000).toISOString(),
      isMine: false,
      isFictional: true,
    };
  });
}
