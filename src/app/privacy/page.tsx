/** Who serves a tile layer, read from its configured URL template (NEXT_PUBLIC_*_TILE_URL or the defaults). */
function tileProvider(template: string): string {
  let host: string;
  try {
    host = new URL(template.replace(/\{[^}]*\}/g, 'a')).hostname;
  } catch {
    return 'ספק המפות';
  }
  if (host === 'openstreetmap.org' || host.endsWith('.openstreetmap.org')) return 'OpenStreetMap';
  if (host.endsWith('arcgisonline.com') || host.endsWith('arcgis.com')) return 'Esri';
  return host;
}

/** "A", "A ו-B": provider names, bidi-isolated. */
function NameList({ names }: { names: string[] }) {
  return (
    <>
      {names.map((n, i) => (
        <Fragment key={n}>
          {i > 0 && ' ו-'}
          <bdi dir="ltr">{n}</bdi>
        </Fragment>
      ))}
    </>
  );
}

